import assert from 'node:assert/strict';
import { matchesRule, selectByRules } from '../../src/rules/rule-matcher.js';
const nested = { gt: 1 };
const frozen = Object.freeze({ kind: 'x', size: nested });
assert.equal(matchesRule(frozen, { kind: 'x', size: 3 }), true);
nested.gt = 4;
assert.equal(matchesRule(frozen, { kind: 'x', size: 3 }), false, 'freezing the outer map must not freeze nested operand behavior');
const mutable = { kind: 'x' };
assert.equal(matchesRule(mutable, { kind: 'x' }), true);
mutable.kind = 'y';
assert.equal(matchesRule(mutable, { kind: 'x' }), false);
let kind = 'x';
const accessor = Object.freeze({ get kind() { return kind; } });
assert.equal(matchesRule(accessor, { kind: 'x' }), true);
kind = 'y';
assert.equal(matchesRule(accessor, { kind: 'x' }), false, 'frozen accessors must remain live');
const rules = Object.freeze([{ match: Object.freeze({ n: { gt: 1 } }), value: 'greater' }, { match: Object.freeze({}), value: 'fallback' }]);
assert.equal(selectByRules(rules, { n: 2 }), 'greater');
assert.equal(selectByRules(rules, { n: 1 }), 'fallback');
assert.equal(selectByRules(rules, {}), 'greater', 'preserve existing missing-value comparison semantics');
console.log('rule-matcher-immutable.test: passed');
