import assert from 'node:assert/strict';
import { layerShape, layerHistory } from '../../demo/ui/activation-grid/data.js';

assert.deepEqual(layerShape(1024), { width:32, height:32 });
assert.deepEqual(layerShape(5120), { width:80, height:64 });
assert.deepEqual(layerShape(7), { width:3, height:3 });
assert.deepEqual(layerShape(1048573), { width:1024, height:1024 },'Large prime widths stay bounded with explicit padding');
const frame = (index, layer, tokenStart, values, forward=0) => ({ index, forward, atMs:index+1,
  layer, tokenStart, tokenIds: values.length === 8 ? [10,11] : [12], status:'captured', values });
const a=frame(0,0,0,[1,1,1,1, 2,0,2,0]);
const b=frame(1,1,0,[0,0,0,0, 3,4,0,0]);
const c=frame(2,0,2,[4,2,4,2],1);
const d=frame(3,1,2,[6,8,0,0],1);
const recording = { trace:{geometry:{layers:2,width:4},frames:[a,b,c,d]} };
let h = layerHistory(recording,Infinity,2,true);
assert.deepEqual(h.positions,[0,1,2]);
assert.deepEqual(h.values,[undefined,1,2,undefined,2.5,2.5], 'RMS preserves opposing signed changes; first position is missing');
h = layerHistory(recording,1,1,true);
assert.deepEqual(h.values,[undefined,1,undefined,undefined,undefined,undefined], 'Capture time and selected position hide future values');
h = layerHistory(recording,Infinity,1,true);
assert.equal(h.values[2],undefined,'Future tokens stay missing even when their capture is available');
const reference = structuredClone(recording);
reference.trace.frames[0].values = [0,0,0,0, 0,0,0,0];
h = layerHistory(recording,Infinity,2,true,reference);
assert.equal(h.values[0],1,'A matched baseline supports a first-position comparison');
assert.equal(h.values[1],Math.sqrt(2));
assert.equal(h.values[2],0);
const failed = {...recording,trace:{...recording.trace,frames:[a,b,c,{...d,status:'dropped',values:null}]}};
assert.equal(layerHistory(failed,Infinity,2,true).values[5],undefined,'A failed layer is not zero');
const retry = {...recording,trace:{...recording.trace,frames:[a,b,c,d,frame(4,0,2,[5,5,5,5],2)]}};
assert.equal(layerHistory(retry,Infinity,2,true).values[5],undefined,'A partial retry never inherits the previous forward pass');
const invalid = {...recording,trace:{...recording.trace,frames:[a,b,c,{...d,values:[1,'NaN',1,1]}]}};
assert.equal(layerHistory(invalid,Infinity,2,true).values[5],'NaN','Invalid and missing values remain distinct');
const gap = {...recording,trace:{...recording.trace,frames:[a,b,{...c,tokenStart:8},{...d,tokenStart:8}]}};
assert.equal(layerHistory(gap,Infinity,8,true).values[2],undefined,'A gap is not silently treated as the adjacent token');
const live = {trace:{geometry:{layers:2,width:4},frames:[a,b,c]}};
assert.equal(layerHistory(live,Infinity,2,true).values[5],undefined);
live.trace.frames.push(d);
assert.equal(layerHistory(live,Infinity,2,true).values[5],2.5,'New live captures fill the existing cell');
console.log('Layer history: layout, RMS, baseline, partial capture, retry, gaps and live append passed');
