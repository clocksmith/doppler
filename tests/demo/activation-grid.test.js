import assert from 'node:assert/strict';
import { createActivationTrace } from '../../src/debug/activation-trace.js';
import { validateRecording, projectFrame, colorGrid, initialColorScale } from '../../demo/ui/activation-grid/data.js';

const limits = { maxBytes: 512, maxFrameBytes: 128, maxFrames: 16, maxGridValues: 64, maxInFlight: 1 };
const geometry = { layers: 2, width: 3 };
const identity = { modelId: 'fixture', manifestHash: 'a'.repeat(64), runtimeVersion: 'test' };
const frames = [];
const trace = createActivationTrace(limits, geometry, identity, frame => frames.push(frame));
const input = new Float32Array([0, 1, -1, 2, 3, 4]);
const boundary = { layer: 0, phase: 'prefill', tokenStart: 0, tokenIds: [11, 12], dtype: 'f32' };
trace.capture(input, boundary);
input.fill(99);
trace.capture(input, { ...boundary, layer: 1 });
assert.equal(trace.snapshot('recording').frames[1].status, 'dropped', 'backpressure is explicit and never blocks inference');
await trace.drain();
assert.deepEqual(trace.snapshot('complete').frames[0].values, [0, 1, -1, 2, 3, 4], 'the snapshot owns its original bytes');
trace.capture(new Float32Array([8, 9, 10]), { ...boundary, phase: 'decode', tokenStart: 2, tokenIds: [13] });
await trace.drain();
const receipt = trace.snapshot('complete');
const recording = { schema: 'doppler.activation-recording/v1', demoBuild: 'fixture',
  display: { layout: 'layer-major-rgb/v1', palette: 'signed-tanh-rgb/v1', scale: 1 }, trace: receipt };
assert.deepEqual(validateRecording(JSON.parse(JSON.stringify(recording))), recording);
const prefill = projectFrame(receipt, 1, 1);
assert.deepEqual(prefill.values.slice(0, 3), [2, 3, 4]);
assert.equal(prefill.values[3], undefined, 'a dropped layer is missing, not zero');
const decode = projectFrame(receipt, 2, 2);
assert.equal(decode.values[3], undefined, 'a new forward never borrows an older layer');
assert.deepEqual(decode.values.slice(0, 3), [8, 9, 10]);
const pixels = colorGrid([-1, 0, 1, undefined, 'NaN'], 1);
assert.equal(pixels.side, 3, 'One scalar per heatmap pixel, padded to a square');
assert.deepEqual([...pixels.rgba.slice(0, 4)], [59, 76, 192, 255]);
assert.deepEqual([...pixels.rgba.slice(4, 8)], [221, 221, 221, 255], 'Signed zero has a neutral color');
assert.deepEqual([...pixels.rgba.slice(8, 12)], [180, 4, 38, 255]);
assert.deepEqual([...pixels.rgba.slice(16, 20)], [255, 0, 255, 255], 'Nonfinite data is visibly invalid');
assert.notDeepEqual([...pixels.rgba.slice(12,16)], [...pixels.rgba.slice(4,8)], 'Missing is not zero');
assert([...pixels.rgba].filter((_,i) => i % 4 === 3).every(a => a === 255), 'Alpha never encodes data');
assert.deepEqual([...colorGrid([0, 1], 1, 'unit').rgba.slice(0, 4)], [20, 20, 55, 255]);
assert.deepEqual([...colorGrid([0, 1], 1, 'unit').rgba.slice(4, 8)], [253, 231, 37, 255]);
const heatmap = structuredClone(recording);
heatmap.display.layout = 'scalar-square/v2'; heatmap.display.palette = 'opaque-heatmap/v1';
assert.deepEqual(validateRecording(heatmap).trace, recording.trace, 'New palette preserves recorded numbers');
assert.equal(initialColorScale([0, undefined, 'NaN'], 1), 1, 'Empty data keeps the declared scale');
assert(initialColorScale([0.0001, 0.0002, 0.0003], 1) < 0.001, 'Small connection products remain visible');
const scaled = structuredClone(recording); scaled.display.scales = { 'weights:overview': 0.002 };
assert.deepEqual(validateRecording(JSON.parse(JSON.stringify(scaled))), scaled);
scaled.display.scales['weights:overview'] = 0;
assert.throws(() => validateRecording(scaled), /Invalid/, 'Saved view scales cannot divide by zero');
const corrupted = structuredClone(recording); corrupted.trace.frames[0].shape = [999, 3];
assert.throws(() => validateRecording(corrupted), /Invalid/);
const oversized = structuredClone(recording); oversized.trace.geometry.layers = 2 ** 30;
assert.throws(() => validateRecording(oversized), /Invalid/);
const capped = createActivationTrace({ ...limits, maxBytes: 24 }, geometry, identity);
capped.capture(new Float32Array(3), { ...boundary, tokenIds: [11] });
await capped.drain();
capped.capture(new Float32Array(3), { ...boundary, layer: 1, tokenIds: [11] });
assert.match(capped.snapshot('complete').stoppedReason, /limit/);
assert.equal(capped.snapshot('complete').recordedBytes, 24);
const rejected = createActivationTrace(limits, geometry, identity, () => { throw new Error('observer failed'); });
rejected.capture(new Float32Array(3), { ...boundary, tokenIds: [11] });
await assert.rejects(rejected.drain(), /observer failed/);
console.log('Activation grid: owned samples, bounded async queue, explicit gaps, cap, fixed scale, provenance and offline round trip passed.');
