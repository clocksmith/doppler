import assert from 'node:assert/strict';
import { UniformBufferCache, getCompletedUniformCache, getUniformCache, releaseUniformBuffer, peekUniformCacheBytes } from '../../src/gpu/uniform-cache.js';
globalThis.GPUBufferUsage = { UNIFORM: 64, COPY_DST: 8 };
function mockDevice() {
  let lose;
  const device = { lost: new Promise(resolve => { lose = resolve; }),
    createBuffer({ size }) { return { size, destroyed: 0, destroy() { this.destroyed++; } }; },
    queue: { writeBuffer(buffer, _offset, data) { buffer.bytes = new Uint8Array(data).slice(); } } };
  return { device, lose };
}
const a = mockDevice(), b = mockDevice();
const cache = new UniformBufferCache(1, 60000, a.device, true);
const data = new Uint32Array([1, 2]).buffer;
const first = cache.getOrCreate(data, 'first'), second = cache.getOrCreate(data, 'second');
assert.equal(first, second);
assert.equal(cache.getStats().outstandingLeases, 2);
new Uint32Array(data)[0] = 99;
assert.deepEqual(Array.from(peekUniformCacheBytes(first)), Array.from(new Uint8Array(new Uint32Array([1, 2]).buffer)));
const transient = cache.getOrCreate(new Uint32Array([3, 4]).buffer, 'all-pinned');
assert.equal(cache.getStats().currentSize, 1);
assert.equal(cache.getStats().pendingDestruction, 0);
assert.equal(cache.getStats().outstandingLeases, 3);
assert.equal(cache.getStats().transientOutstandingLeases, 1);
releaseUniformBuffer(transient); assert.equal(transient.destroyed, 1);
assert.equal(cache.getStats().outstandingLeases, 2);
assert.equal(cache.getStats().transientOutstandingLeases, 0);
releaseUniformBuffer(first); assert.equal(first.destroyed, 0);
cache.clear(); assert.equal(first.destroyed, 0, 'Clear cannot retire remaining in-flight lease');
assert.equal(cache.getStats().retiredActiveEntries, 1);
assert.equal(cache.getStats().outstandingLeases, 1);
cache.clear(); assert.equal(cache.getStats().retiredActiveEntries, 1);
releaseUniformBuffer(second); assert.equal(first.destroyed, 1);
assert.equal(cache.getStats().retiredActiveEntries, 0);
assert.equal(cache.getStats().outstandingLeases, 0);
const completed = cache.getOrCreate(data, 'completed'); releaseUniformBuffer(completed);
const replacement = cache.getOrCreate(new Uint32Array([5, 6]).buffer, 'replace-completed');
assert.equal(completed.destroyed, 1); assert.equal(replacement.destroyed, 0);
releaseUniformBuffer(replacement); cache.clear(); assert.equal(replacement.destroyed, 1);
assert.notEqual(getCompletedUniformCache(a.device), getCompletedUniformCache(b.device));
assert.notEqual(getCompletedUniformCache(a.device), getUniformCache(a.device));
const lossCache = getCompletedUniformCache(b.device);
const active = lossCache.getOrCreate(data, 'loss-active');
b.lose({ reason: 'destroyed' }); await Promise.resolve(); await Promise.resolve();
assert.throws(() => getCompletedUniformCache(b.device), /live device/);
assert.equal(active.destroyed, 0);
assert.equal(lossCache.getStats().outstandingLeases, 1);
assert.equal(lossCache.getStats().retiredActiveEntries, 1);
releaseUniformBuffer(active); assert.equal(active.destroyed, 1);
assert.equal(lossCache.getStats().outstandingLeases, 0);
assert.equal(lossCache.getStats().retiredActiveEntries, 0);
const fallbackLoss = mockDevice();
const fallbackCache = new UniformBufferCache(0, 60000, fallbackLoss.device, true);
const fallbackActive = fallbackCache.getOrCreate(data, 'fallback-loss');
fallbackLoss.lose({ reason: 'destroyed' }); await Promise.resolve(); await Promise.resolve();
assert.equal(fallbackActive.destroyed, 0);
assert.equal(fallbackCache.getStats().transientOutstandingLeases, 1);
releaseUniformBuffer(fallbackActive); releaseUniformBuffer(fallbackActive);
assert.equal(fallbackActive.destroyed, 1);
assert.equal(fallbackCache.getStats().outstandingLeases, 0);
assert.equal(fallbackCache.getStats().transientOutstandingLeases, 0);
const legacy = new UniformBufferCache(1, 60000, a.device);
const old = legacy.getOrCreate(data, 'old'); legacy.getOrCreate(new Uint32Array([7, 8]).buffer, 'new');
assert.equal(old.destroyed, 0); assert.equal(legacy.getStats().pendingDestruction, 1);
legacy.flushPendingDestruction(); assert.equal(old.destroyed, 1); legacy.clear();
console.log('completed uniform leases: immutable, bounded, isolated, completion-aware; legacy behavior unchanged');
