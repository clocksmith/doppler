#!/usr/bin/env node
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { resolveKernelConfig } from '../src/config/schema/kernel-registry.schema.js';
import { compareUniformInterface, reflectWgslInterface } from './lib/wgsl-interface.js';

const repoRoot = fileURLToPath(new URL('../', import.meta.url));
const banner = '// Generated by tools/generate-kernel-uniforms.js from src/config/kernels/registry.json.\n// Do not edit; npm run kernels:uniforms:sync.\n';
const encoders = { u32: 'writeU32', i32: 'writeI32', f32: 'writeF32' };

export async function generateKernelUniforms(root) {
  const registry = JSON.parse(await fs.readFile(path.join(root, 'src/config/kernels/registry.json'), 'utf8'));
  const reflected = new Map();
  const layouts = new Map();
  const kernels = [];
  const errors = [];
  for (const [operation, schema] of Object.entries(registry.operations)) {
    for (const [variant, spec] of Object.entries(schema.variants)) {
      const config = resolveKernelConfig(operation, variant, schema, spec);
      const kernel = `${operation}/${variant}`;
      if (!reflected.has(config.wgsl)) {
        const source = await fs.readFile(path.join(root, 'src/gpu/kernels', config.wgsl), 'utf8');
        reflected.set(config.wgsl, reflectWgslInterface(source));
      }
      const actual = reflected.get(config.wgsl);
      errors.push(...compareUniformInterface(config.uniforms, actual.uniforms, kernel));
      for (const binding of config.bindings) {
        if (binding.wgslName === undefined) continue;
        const declaration = actual.bindings.find((candidate) => candidate.name === binding.wgslName);
        if (!declaration || declaration.group !== 0 || declaration.index !== binding.index || declaration.type !== binding.type) {
          errors.push(`${kernel}: binding ${binding.name} disagrees with WGSL variable ${binding.wgslName}.`);
        }
      }
      if (spec.bindings && spec.bindings.every((binding) => binding.wgslName !== undefined)
        && spec.bindings.length !== actual.bindings.length) errors.push(`${kernel}: complete binding declaration omits a WGSL resource.`);
      if (!actual.entryPoints.includes(config.entryPoint)) errors.push(`${kernel}: WGSL entry point is missing.`);
      if (config.uniforms == null) continue;
      const fields = config.uniforms.fields;
      if (!Array.isArray(fields)) continue;
      const names = new Set();
      for (const field of fields) {
        if (field.padding && actual.memberReferences.includes(field.name)) {
          errors.push(`${kernel}: ${field.name} is read by WGSL and cannot be designated padding.`);
        }
        if (names.has(field.name)) errors.push(`${kernel}: duplicate uniform ${field.name}.`);
        names.add(field.name);
        if (!encoders[field.type]) errors.push(`${kernel}: unsupported generated uniform type ${field.type}.`);
        if (field.padding !== undefined && typeof field.padding !== 'boolean') {
          errors.push(`${kernel}: padding must be a boolean for ${field.name}.`);
        }
      }
      const key = JSON.stringify(config.uniforms);
      if (!layouts.has(key)) layouts.set(key, { name: `write_${operation}_${variant}`, uniforms: config.uniforms });
      kernels.push({ kernel, layout: layouts.get(key) });
    }
  }
  if (errors.length) throw new Error(`Kernel interface mismatches:\n${errors.join('\n')}`);

  // Deterministic source shards keep generated declarations and direct writes
  // reviewable under the same source line limit as hand-written modules.
  const files = new Map();
  const shards = [];
  let shard;
  for (const layout of layouts.values()) {
    const body = [`export function ${layout.name}(view, values, kernel) {`];
    for (const field of layout.uniforms.fields) {
      body.push(field.padding
        ? `  view.setUint32(${field.offset}, 0, true);`
        : `  ${encoders[field.type]}(view, ${field.offset}, values[${JSON.stringify(field.name)}], kernel, ${JSON.stringify(field.name)});`);
    }
    body.push('}', '');
    if (!shard || shard.lines.length + body.length > 600) {
      shard = { id: shards.length, lines: [], layouts: [] };
      shards.push(shard);
    }
    shard.lines.push(...body);
    shard.layouts.push(layout);
    layout.shard = shard.id;
  }
  for (const part of shards) {
    const base = `src/gpu/kernels/generated/uniform-writers-${part.id}`;
    files.set(`${base}.js`, banner + "import { writeU32, writeI32, writeF32 } from '../uniform-encoding.js';\n\n" + part.lines.join('\n'));
    const declarations = part.layouts.map((layout) => {
      const fields = layout.uniforms.fields.filter((field) => !field.padding)
        .map((field) => `${JSON.stringify(field.name)}: number`).join('; ');
      return `export declare function ${layout.name}(view: DataView, values: { ${fields} }, kernel: string): void;`;
    });
    files.set(`${base}.d.ts`, banner + declarations.join('\n') + '\n');
  }
  const imports = shards.map((part) => `import * as writers${part.id} from './uniform-writers-${part.id}.js';`);
  const entries = kernels.map(({ kernel, layout }) => `  ${JSON.stringify(kernel)}: { size: ${layout.uniforms.size}, write: writers${layout.shard}.${layout.name} },`);
  files.set('src/gpu/kernels/generated/uniform-writers.js', banner + imports.join('\n') + '\n\nexport const UNIFORM_WRITERS = Object.freeze({\n' + entries.join('\n') + '\n});\n');
  const types = kernels.map(({ kernel, layout }) => `  ${JSON.stringify(kernel)}: Parameters<typeof writers${layout.shard}.${layout.name}>[1];`);
  files.set('src/gpu/kernels/generated/uniform-writers.d.ts', banner + imports.join('\n') + '\n\nexport interface KernelUniformValues {\n' + types.join('\n') + '\n}\nexport declare const UNIFORM_WRITERS: { readonly [K in keyof KernelUniformValues]: { readonly size: number; readonly write: (view: DataView, values: KernelUniformValues[K], kernel: string) => void } };\n');
  return { files, variants: kernels.length, modules: reflected.size, layouts: layouts.size };
}

async function main() {
  const result = await generateKernelUniforms(repoRoot);
  const check = process.argv.includes('--check');
  const directory = path.join(repoRoot, 'src/gpu/kernels/generated');
  const existing = await fs.readdir(directory).catch((error) => { if (error.code === 'ENOENT') return []; throw error; });
  const stale = [];
  for (const [relative, content] of result.files) {
    const target = path.join(repoRoot, relative);
    const current = await fs.readFile(target, 'utf8').catch((error) => { if (error.code === 'ENOENT') return null; throw error; });
    if (current === content) continue;
    if (check) stale.push(relative);
    else { await fs.mkdir(path.dirname(target), { recursive: true }); await fs.writeFile(target, content); }
  }
  for (const name of existing.filter((name) => /^uniform-writers(?:-\d+)?\.(?:js|d\.ts)$/.test(name))) {
    const relative = `src/gpu/kernels/generated/${name}`;
    if (result.files.has(relative)) continue;
    if (check) stale.push(relative);
    else await fs.unlink(path.join(repoRoot, relative));
  }
  if (stale.length) throw new Error(`Stale generated uniform writers; run npm run kernels:uniforms:sync:\n${stale.join('\n')}`);
  console.log(`[kernels:uniforms] ${result.variants} variants, ${result.modules} WGSL modules, ${result.layouts} shared layouts; ${check ? 'checked' : 'generated'}.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => { console.error(error.message); process.exitCode = 1; });
}
