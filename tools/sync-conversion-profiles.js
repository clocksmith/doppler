#!/usr/bin/env node
// Conversion profile authoring. Shared definitions under
// tools/conversion-authoring expand into the committed v1 profile JSON under
// src/config/conversion byte for byte, so repeated execution objects are
// written once and every consumer keeps reading the expanded profile.
// `--check` fails when a committed profile drifts from its authoring source.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const AUTHORING_ROOT = 'tools/conversion-authoring';
export const AUTHORING_SCHEMA = 'doppler.conversion-profile-authoring/v1';
const TARGET_ROOT = 'src/config/conversion/';

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

function listAuthoringFiles(root) {
  const base = path.join(root, AUTHORING_ROOT);
  if (!fs.existsSync(base)) return [];
  const files = [];
  const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (entry.isFile() && entry.name.endsWith('.authoring.json')) files.push(full);
    }
  };
  walk(base);
  return files.sort();
}

// Every object of the form { "$ref": "relative/file.json" } is replaced by
// that file's expanded content. References stay inside the authoring root and
// cannot form cycles.
export function expandReferences(node, baseDir, root, trail = []) {
  if (Array.isArray(node)) return node.map((entry) => expandReferences(entry, baseDir, root, trail));
  if (!node || typeof node !== 'object') return node;
  if (typeof node.$ref === 'string') {
    if (Object.keys(node).length !== 1) throw new Error(`A $ref object carries only $ref: ${JSON.stringify(node)}`);
    const file = path.resolve(baseDir, node.$ref);
    const authoringRoot = path.join(root, AUTHORING_ROOT) + path.sep;
    if (!file.startsWith(authoringRoot)) throw new Error(`$ref leaves ${AUTHORING_ROOT}: ${node.$ref}`);
    if (trail.includes(file)) throw new Error(`$ref cycle through ${path.relative(root, file)}`);
    return expandReferences(readJson(file), path.dirname(file), root, [...trail, file]);
  }
  return Object.fromEntries(Object.entries(node).map(([key, value]) => [key, expandReferences(value, baseDir, root, trail)]));
}

export function renderProfile(profile) {
  return `${JSON.stringify(profile, null, 2)}\n`;
}

export function loadAuthoring(file, root = ROOT) {
  const authoring = readJson(file);
  const relative = path.relative(root, file);
  if (authoring?.schema !== AUTHORING_SCHEMA) throw new Error(`${relative}: schema must be ${AUTHORING_SCHEMA}`);
  if (typeof authoring.target !== 'string' || !authoring.target.startsWith(TARGET_ROOT) || !authoring.target.endsWith('.json')) {
    throw new Error(`${relative}: target must be a profile path under ${TARGET_ROOT}`);
  }
  if (!authoring.profile || typeof authoring.profile !== 'object' || Array.isArray(authoring.profile)) {
    throw new Error(`${relative}: profile must be an object`);
  }
  return { file: relative, target: authoring.target, content: renderProfile(expandReferences(authoring.profile, path.dirname(file), root)) };
}

// Returns one row per authoring file: { file, target, status } where status is
// "current", "drifted" or "missing" against the committed profile.
export function syncConversionProfiles({ root = ROOT, write = false } = {}) {
  const rows = [];
  const targets = new Set();
  for (const file of listAuthoringFiles(root)) {
    const { file: relative, target, content } = loadAuthoring(file, root);
    if (targets.has(target)) throw new Error(`${relative}: ${target} is generated by more than one authoring file`);
    targets.add(target);
    const targetPath = path.join(root, target);
    const existing = fs.existsSync(targetPath) ? fs.readFileSync(targetPath, 'utf8') : null;
    const status = existing === null ? 'missing' : existing === content ? 'current' : 'drifted';
    if (write && status !== 'current') fs.writeFileSync(targetPath, content);
    rows.push({ file: relative, target, status });
  }
  return rows;
}

function main(argv) {
  const check = argv.includes('--check');
  const rows = syncConversionProfiles({ write: !check });
  const stale = rows.filter((row) => row.status !== 'current');
  for (const row of rows) console.log(`${check ? row.status : (row.status === 'current' ? 'current' : 'wrote')} ${row.target} <- ${row.file}`);
  if (check && stale.length) {
    console.error(`conversion profiles drift from their authoring sources (${stale.length}); run npm run conversion:profiles:sync`);
    process.exitCode = 1;
  } else {
    console.log(`conversion profiles: ${rows.length} authored profile(s) ${check ? 'current' : 'synchronized'}`);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  main(process.argv.slice(2));
}
