#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const contract = JSON.parse(await readFile(resolve(root, 'src/config/generation-contract.json'), 'utf8'));
const fieldType = rule => rule.type === 'array' ? `${rule.items === 'integer' ? 'number' : rule.items}[]`
  : rule.type === 'integer' ? 'number' : rule.type;
const properties = (fields, resolved = false) => Object.entries(fields).map(([name, rule]) =>
  `  ${name}${rule.required || (resolved && Object.hasOwn(rule, 'default')) ? '' : '?'}: ${fieldType(rule)};`).join('\n');
const output = `// Generated by tools/sync-generation-contract.js. Edit generation-contract.json.\n`
  + `export interface GenerationOptions {\n${properties(contract.options)}\n}\n`
  + `export interface ResolvedGenerationOptions {\n${properties(contract.options, true)}\n}\n`
  + `export type GenerationInput = ${contract.inputExactlyOne.map(selected => `{ ${Object.entries(contract.input).map(([name, rule]) => name === selected ? `${name}: ${fieldType(rule)}` : `${name}?: never`).join('; ')} }`).join(' | ')};\n`
  + `export type GenerationStoppingReason = ${contract.stoppingReasons.map(value => JSON.stringify(value)).join(' | ')};\n`
  + `export interface GenerationCompletion { schema: ${JSON.stringify(contract.completionSchema)}; stopReason: GenerationStoppingReason; promptTokenCount: number; generatedTokenCount: number; }\n`
  + `export interface GenerationOutput { text: string; tokenIds: number[]; sampling: ResolvedGenerationOptions; completion: GenerationCompletion; }\n`
  + `export const GENERATION_CONTRACT: Readonly<{ schema: ${JSON.stringify(contract.schema)}; input: Readonly<Record<string, Readonly<Record<string, unknown>>>>; inputExactlyOne: readonly string[]; options: Readonly<Record<keyof GenerationOptions, Readonly<Record<string, unknown>>>>; completionSchema: ${JSON.stringify(contract.completionSchema)}; stoppingReasons: readonly GenerationStoppingReason[]; errors: Readonly<Record<${Object.keys(contract.errors).map(value => JSON.stringify(value)).join(' | ')}, string>>; }>;\n`
  + `export class GenerationError extends Error { readonly code: string; constructor(kind: keyof typeof GENERATION_CONTRACT.errors, message: string, options?: ErrorOptions); }\n`
  + `export function validateGenerationField(name: string, value: unknown, rule?: Readonly<Record<string, unknown>>): void;\n`
  + `export function validateGenerationInput(input: unknown): asserts input is GenerationInput;\n`
  + `export function resolveGenerationOptions(options: unknown): Readonly<ResolvedGenerationOptions>;\n`;
const target = resolve(root, 'src/config/generation-contract.d.ts');
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== output) throw new Error('Generation declarations are stale; run tools/sync-generation-contract.js.');
  console.log('Generation declarations match the public definition.');
} else {
  await writeFile(target, output);
  console.log('Generated public generation declarations.');
}
